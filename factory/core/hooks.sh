#!/usr/bin/env bash
# The hook config generator and its drift check (lib/hooks.sh). Run from the
# project root:
#   bash factory/core/hooks.sh generate   write the "hooks" key of .claude/settings.json
#                                         from its source, its "model",
#                                         "effortLevel" and "maxEffortLevel" keys
#                                         and the Lock lift's rule in its
#                                         "permissions" "allow" list (lib/hooks.sh);
#                                         remove the retired Cursor files
#   bash factory/core/hooks.sh check      print a finding per drifted file; exit 1 on any
#
# check is what prepare runs (the runner calls it after the pin check). On a project
# with a hook mode (tools/verify/hook-mode) it fails when a generated file differs
# from what generate would write (a lift-rule finding when all it lacks is the
# Lock lift's allow rule), when a retired file is still there, and when
# core.hooksPath is unset or resolves to
# neither the running Core's githooks nor this checkout's own copy of them; a fresh
# clone has no core.hooksPath, since it is local config. The own copy counts because
# the Sonnet Editor's stop hook runs the main checkout's Core in a linked worktree,
# where the relative core.hooksPath adopt.sh sets is the worktree's copy, the one git
# runs there. A project without a hook mode has not adopted the hooks, and passes.
#
# generate is idempotent: a second run writes the same bytes. It does not set
# core.hooksPath (adopt.sh does).
#
# Exit codes: 0 ok, 1 drift (check) or an unreadable settings file, 2 usage.
set -u

core="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
. "$core/lib/steps.sh"
. "$core/lib/findings.sh"
. "$core/lib/hooks.sh"

usage() {
	echo "usage: bash factory/core/hooks.sh generate|check" >&2
	exit 2
}

[ "$#" -eq 1 ] || usage
case "$1" in generate | check) ;; *) usage ;; esac

tmp="$(mktemp -d)"
trap 'rm -rf "$tmp"' EXIT

# render [settings-file]: write the generated settings into $tmp/claude. False
# when the settings file is not a JSON object, or its "permissions" or their
# "allow" is of another type.
render() {
	factory_settings_render "${1:-$FACTORY_CLAUDE_SETTINGS}" "$core/hooks/claude-hooks.json" > "$tmp/claude"
}

# same <generated> <file>: true when the file holds the generated bytes (CRs aside).
same() {
	[ -f "$2" ] && tr -d '\r' < "$2" | cmp -s "$1" -
}

regenerate="run bash factory/core/hooks.sh generate"

if [ "$1" = generate ]; then
	if ! render; then
		echo "hooks: $FACTORY_CLAUDE_SETTINGS is not a JSON object, or its \"permissions\" or their \"allow\" is of another type; fix it by hand, then generate again" >&2
		exit 1
	fi
	same "$tmp/claude" "$FACTORY_CLAUDE_SETTINGS" || { mkdir -p "$(dirname "$FACTORY_CLAUDE_SETTINGS")" && cp "$tmp/claude" "$FACTORY_CLAUDE_SETTINGS"; } || exit 1
	removed=0
	while IFS= read -r retired; do
		rm -f "$retired" || exit 1
		removed=1
	done < <(factory_retired_hook_files)
	# The folder goes too once the factory's files were all it held.
	[ "$removed" -eq 0 ] || rmdir .cursor 2> /dev/null
	exit 0
fi

check() {
	local bad=0 path want own got retired
	[ -f "$FACTORY_HOOK_MODE_FILE" ] || return 0
	if ! factory_hook_mode > /dev/null; then
		factory_finding "$FACTORY_HOOK_MODE_FILE" 1 hook-mode "expected 'report' (Adopted) or 'enforce' (Armed)"
		bad=1
	fi
	if ! render || ! factory_json_allow "$FACTORY_CLAUDE_SETTINGS" "$FACTORY_LIFT_RULE" > "$tmp/allowed"; then
		factory_finding "$FACTORY_CLAUDE_SETTINGS" 1 hook-drift "not a JSON object, or its \"permissions\" or their \"allow\" is of another type, so its hooks can't be generated"
		bad=1
	elif ! same "$tmp/claude" "$FACTORY_CLAUDE_SETTINGS"; then
		# One finding for the file: the keys are judged on it with the lift rule in
		# place, and a file whose keys are right lacks only that rule.
		bad=1
		if [ ! -f "$FACTORY_CLAUDE_SETTINGS" ] || ! render "$tmp/allowed" || ! same "$tmp/claude" "$tmp/allowed"; then
			factory_finding "$FACTORY_CLAUDE_SETTINGS" 1 hook-drift "its \"hooks\", \"model\", \"effortLevel\" or \"maxEffortLevel\" key differs from what the factory writes (factory/core/hooks/claude-hooks.json, lib/hooks.sh); set your own model in .claude/settings.local.json, then $regenerate"
		else
			factory_finding "$FACTORY_CLAUDE_SETTINGS" 1 lift-rule "its \"permissions\" \"allow\" list lacks the factory's rule for the Lock lift, $FACTORY_LIFT_RULE (lib/hooks.sh); $regenerate"
		fi
	fi
	while IFS= read -r retired; do
		factory_finding "$retired" 1 hook-drift "the retired Cursor Editor's; $regenerate"
		bad=1
	done < <(factory_retired_hook_files)
	want="$(cd "$core/hooks/githooks" && pwd -P)"
	own="$(cd "$FACTORY_GITHOOKS_DIR" 2> /dev/null && pwd -P)"
	path="$(git config --get core.hooksPath 2> /dev/null)"
	if [ -z "$path" ]; then
		factory_finding "$FACTORY_HOOK_MODE_FILE" 1 hooks-path "core.hooksPath is unset, so no git hook runs; run git config core.hooksPath $FACTORY_GITHOOKS_DIR"
		bad=1
	else
		got="$(cd "$path" 2> /dev/null && pwd -P)"
		# A path that doesn't resolve is empty, as is the own copy of a project with no
		# vendored factory/; that must stay a finding, not a match.
		if [ -z "$got" ] || { [ "$got" != "$want" ] && [ "$got" != "$own" ]; }; then
			factory_finding "$FACTORY_HOOK_MODE_FILE" 1 hooks-path "core.hooksPath is $path, not the Core's githooks; run git config core.hooksPath $FACTORY_GITHOOKS_DIR"
			bad=1
		fi
	fi
	return "$bad"
}

check > "$tmp/findings"
status=$?
factory_sort_findings < "$tmp/findings"
exit "$status"
