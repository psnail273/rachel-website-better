#!/usr/bin/env bash
# The Next.js adapter's verify-<project> skill generator; factory/core/verify-skill.sh
# runs it from the project root and checks what it writes:
#   bash factory/adapters/nextjs/verify-skill.sh <project> <dir>
#
# It writes <dir>/SKILL.md (Launch, Doctor, Drive, Evidence, Cleanup),
# <dir>/feature-map.md, and the two helpers a check by hand runs, copied as they
# are from verify-skill-helpers/ beside it: app.sh (the production app on a free
# port, started and stopped by its own pid) and contrast.mjs (a text box's
# contrast, read from screenshots once transitions settle). It reads the
# project's files only, so two runs write the same bytes:
#   - package.json: the name;
#   - the App Router folder, app/ or src/app/: its routes, for the feature map;
#   - tools/*.sh other than verify.sh: each one's first header sentence;
#   - docs/agents/devices.md and CONTEXT-MAP.md or CONTEXT.md, when present.
# The feature map has a row per page (page.tsx, .ts, .jsx, .js, .mdx) and per
# route handler (route.ts, .js): its URL path (route groups `(name)` and parallel
# slots `@name` left out; a `_private` folder routes nothing), its file, and the
# test files in its folder. Files come from git (tracked and untracked, not
# ignored, and still on disk) at a checkout's root, else from find. Exits 1 when
# it cannot write.
set -u

[ "$#" -eq 2 ] || {
	echo "usage: verify-skill.sh <project> <dir>" >&2
	exit 2
}
project="$1"
dir="$2"
skill="verify-$project"
helpers="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)/verify-skill-helpers"

files() {
	if [ -z "$(git rev-parse --show-prefix 2> /dev/null || echo no)" ]; then
		git -c core.quotepath=off ls-files -co --exclude-standard | while IFS= read -r f; do
			[ -f "$f" ] && printf '%s\n' "$f"
		done
	else
		find . -type f -not -path './node_modules/*' -not -path './.next/*' | sed 's#^\./##'
	fi | LC_ALL=C sort
}

# header <script>: the first sentence of the script's header comment.
header() {
	tr -d '\r' < "$1" | awk '
		NR == 1 && /^#!/ { next }
		!/^#/ || /^#[ \t]*$/ || /^#   / { exit }
		{ sub(/^#[ \t]*/, ""); text = text (text == "" ? "" : " ") $0 }
		END {
			i = index(text, ". ")
			if (i) text = substr(text, 1, i)
			sub(/:$/, ".", text)
			print text
		}
	'
}

listing="$(files)"

name=""
[ -f package.json ] && name="$(tr -d '\r' < package.json | sed -n 's/^  "name": *"\([^"]*\)",*$/\1/p' | head -n 1)"
[ -n "$name" ] || name="$project"
router=""
printf '%s\n' "$listing" | grep -q '^app/' && router="app"
[ -z "$router" ] && printf '%s\n' "$listing" | grep -q '^src/app/' && router="src/app"
health=""
[ -n "$router" ] && printf '%s\n' "$listing" | grep -qE "^$router/api/health/route\.(ts|js)$" && health="/api/health"
tools="$(printf '%s\n' "$listing" | grep -E '^tools/[^/]+\.sh$' | grep -vxF tools/verify.sh)"
context=""
[ -f CONTEXT.md ] && context="CONTEXT.md"
[ -f CONTEXT-MAP.md ] && context="CONTEXT-MAP.md"
devices=""
[ -f docs/agents/devices.md ] && devices="docs/agents/devices.md"

mkdir -p "$dir" || exit 1
cp "$helpers/app.sh" "$helpers/contrast.mjs" "$dir/" || exit 1

# A description has at most 200 characters (skill-budget.sh), so a long name is
# left out of it.
description="Launch, drive and inspect the running $name app (Next.js), its pages and API routes, and collect evidence. Use for smoke checks, bug repros and criteria that need a running app."
[ "${#description}" -le 200 ] ||
	description="Launch, drive and inspect this project's running Next.js app, its pages and API routes, and collect evidence. Use for smoke checks, bug repros and criteria that need a running app."

{
	cat << EOF
---
name: $skill
description: $description
---

# $skill

Generated by \`bash factory/core/verify-skill.sh\` from the project's files; rerun it with \`--force\` after the layout changes (hand edits are lost then). Run everything from the project root, in a shell set up as the steps set theirs: \`set -a; . tools/verify/local.env; set +a; . tools/verify/_nextjs.sh\` (\`NODE_BIN\` and \`PNPM_BIN\` in \`local.env\` name Node and pnpm when they aren't on PATH, and \`_nextjs.sh\` puts them first on it; the versions are pinned in \`tools/verify/pins\`). Scratch output (logs, screenshots, PIDs) goes under \`.next/factory/\`, which is never tracked; \`mkdir -p .next/factory\` first.

## Launch

- **Dev server**, in the background: \`pnpm exec next dev --port 3100 > .next/factory/dev.log 2>&1 & echo \$! > .next/factory/dev.pid\`. It is ready when \`curl -fsS -o /dev/null http://localhost:3100/\` succeeds: retry that until it does (or the log shows an error), never a fixed sleep.
- **Production build, for a check**: \`bash .claude/skills/$skill/app.sh start\` builds (under the build lock), starts \`next start\` on a free port with smoke's environment (\`tools/verify/smoke-env\`), waits until it is Ready and prints \`url\`, \`pid\`, \`env\` and \`log\` lines, then leaves it running. \`app.sh run <command...>\` runs a command (a Playwright script) with \`APP_URL\` and \`PLAYWRIGHT_BROWSERS_PATH\` set (local.env's, else its \`FACTORY_PLAYWRIGHT_BROWSERS\`) and Node first on PATH. Its header says the rest.
- **Production build, for the human**: \`bash tools/verify/playtest\` runs \`next build\` and prints the \`next start\` command.
EOF
	if [ -n "$health" ]; then
		echo "- **Health**: \`curl -fsS http://localhost:3100$health\` answers when the server is up."
	fi
	if [ -n "$devices" ]; then
		echo "- **On a device**: read \`$devices\` first; it says which device and how."
	fi
	if [ -n "$tools" ]; then
		echo "- **Project tools** (each script's header says how to use it):"
		printf '%s\n' "$tools" | while IFS= read -r t; do
			about="$(header "$t")"
			echo "  - \`bash $t\`${about:+: $about}"
		done
	fi
	cat << 'EOF'

## Doctor

When a launch fails, or before the first one on a machine:

1. `bash tools/verify.sh prepare`: tool locations, pins, the offline install, `next typegen` and the scope cross-check. Fix its findings first: `node-missing` or `pnpm-missing` means `tools/verify/local.env`; `install-failed` means run `bash tools/verify/bootstrap` (it may use the network), then prepare again.
2. `"${NODE_BIN:-node}" --version` prints the Node version `tools/verify/pins` names.
3. `EADDRINUSE` in the log: another server holds the port. Find it with `lsof -i :3100` (or `ss -ltnp`); stop it if you started it, else pick another port.
4. Odd errors after a pull or a branch switch: rerun prepare (it reinstalls and regenerates the route types); if they stay, stop the server and `rm -rf .next`.

## Drive

- **HTTP**: `curl -sS -i http://localhost:3100<path>` for a page or an API route from the [feature map](feature-map.md); `-X POST -H 'content-type: application/json' -d '<json>'` for a handler that takes a body.
- **Scripted, the durable way**: a Vitest test that calls the route handler or the function directly. Write it with `write-tests-nextjs`; run one file with `pnpm exec vitest run <file>`.
- **In a browser**: a one-off Playwright script (`@playwright/test` is installed) that opens the URL headless (`chromium.launch()`), clicks and reads the page. bootstrap installed that browser, with Firefox and WebKit (Safari's engine: `firefox.launch()`, `webkit.launch()`), where `PLAYWRIGHT_BROWSERS_PATH` (`tools/verify/local.env`) says; the smoke step loads every page in all three. Its page checks (axe at 390 and 1280 px, reflow at 320 px, focus in forced colours, links) run on their own against a running server too, with a cookie set (a design direction's): `"${NODE_BIN:-node}" tools/verify/_smoke_page.mjs http://localhost:3100 60 [--cookie <name>=<value>] <route>...` prints the findings smoke would. On a page that carries the layout contract's `[data-shell]` (its attributes and tokens are in `tools/verify/_layout.mjs`'s header), the layout check runs alone the same way, at 390, 768, 1280 and 1920 px: `"${NODE_BIN:-node}" tools/verify/_layout.mjs http://localhost:3100 60 [--cookie <name>=<value>] <route>...` prints smoke's layout findings, then a `reported:` line for each one-word line, ragged or short paragraph, and on stderr which routes it checked and which it skipped for want of `[data-shell]`. A headed browser is another download, `pnpm exec playwright install chromium`, which uses the network: ask the human first.
EOF
	sed "s/@SKILL@/$skill/g" << 'EOF'

## Evidence

Evidence for a criterion is the command, its exit code, and the lines or files that show the behaviour. Quote them; never paraphrase a log.

- **Response**: the status line, the headers the criterion names and the body, from `curl -sS -i`.
- **Server log**: `.next/factory/dev.log`. An error is an `⨯` or `Error:` line with a stack after it; quote the whole block. The server keeps running after a request fails, so read the log, not only the exit code.
- **Tests**: Vitest's summary lines (`Test Files`, `Tests`) and each failing test's message.
- **Screenshot**: from Playwright, `await page.screenshot({ path: ".next/factory/<name>.png" })`.
- **Browser console**: Playwright's `page.on("console", ...)` and `page.on("pageerror", ...)`, printed one line each with a fixed prefix you can grep.
- **Contrast of a text box**: `bash .claude/skills/@SKILL@/app.sh contrast <route> '<selector>' [--width <px>] [--scheme dark] [--cookie <name>=<value>] [--save .next/factory/<name>]` on the started app (`node .claude/skills/@SKILL@/contrast.mjs <url> '<selector>' ...` on any URL). It finishes every animation and transition and turns them off before it reads, so no colour is caught mid-way, then compares the box's screenshot with one of the text made transparent. It prints `contrast <ratio>:1` (WCAG's, cut to two decimals), the `text` and `background` colours, and the `worst` ratio against what lies right under the text (an image, a gradient). Quote those lines; never read a colour from `getComputedStyle` while a transition may run.
EOF
	sed "s/@SKILL@/$skill/g" << 'EOF'

## Cleanup

Leave the machine and the tree as you found them:

- Stop every server you started: `bash .claude/skills/@SKILL@/app.sh stop` stops what `app.sh start` started (its own process groups, by the pids it kept, nothing else), and `kill "$(cat .next/factory/dev.pid)"` a dev server. Never `pkill`: it reaches other checks' servers, and auto mode refuses it. Check: `pgrep -fl 'next (dev|start)'` lists none of yours.
- Delete your probe scripts and screenshots, and anything you wrote outside `.next/factory/`; `git status` shows only your intended changes.
EOF
	cat << EOF

## Feature map

[\`feature-map.md\`](feature-map.md): each page and API route with its URL path, its file and the tests beside it.${context:+ Names follow \`$context\`.}
EOF
} > "$dir/SKILL.md" || exit 1

{
	echo "# $name feature map"
	echo
	if [ -n "$router" ]; then
		echo "Generated with \`$skill\`. Each page and route handler under \`$router/\`, with the test files in its folder."
	else
		echo "Generated with \`$skill\`. The project has no App Router folder (\`app/\` or \`src/app/\`), so no routes."
	fi
	echo
	echo "| Path | Kind | File | Tests |"
	echo "| --- | --- | --- | --- |"
	[ -z "$router" ] || printf '%s\n' "$listing" | awk -v root="$router/" '
		{ all[NR] = $0 }
		END {
			for (i = 1; i <= NR; i++) {
				f = all[i]
				if (index(f, root) != 1) continue
				rest = substr(f, length(root) + 1)
				n = split(rest, part, "/")
				if (part[n] ~ /^page\.(tsx|ts|jsx|js|mdx)$/) kind = "page"
				else if (part[n] ~ /^route\.(ts|js)$/) kind = "API"
				else continue
				path = ""; private = 0
				for (j = 1; j < n; j++) {
					if (part[j] ~ /^_/) private = 1
					if (part[j] ~ /^\(.*\)$/ || part[j] ~ /^@/) continue
					path = path "/" part[j]
				}
				if (private) continue
				if (path == "") path = "/"
				folder = substr(f, 1, length(f) - length(part[n]))
				tests = ""
				for (k = 1; k <= NR; k++) {
					t = all[k]
					if (index(t, folder) != 1) continue
					leaf = substr(t, length(folder) + 1)
					if (leaf ~ /\// || leaf !~ /\.test\.(ts|tsx|js|jsx|mts)$/) continue
					tests = tests (tests == "" ? "" : ", ") "`" leaf "`"
				}
				printf "| `%s` | %s | `%s` | %s |\n", path, kind, f, (tests == "" ? "none" : tests)
			}
		}
	' | LC_ALL=C sort
} > "$dir/feature-map.md" || exit 1
