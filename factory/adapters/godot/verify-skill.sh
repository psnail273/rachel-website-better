#!/usr/bin/env bash
# The Godot adapter's verify-<project> skill generator; factory/core/verify-skill.sh
# runs it from the project root and checks what it writes:
#   bash factory/adapters/godot/verify-skill.sh <project> <dir>
#
# It writes <dir>/SKILL.md (Launch, Doctor, Drive, Evidence, Cleanup) and
# <dir>/feature-map.md, from the project's files only, so two runs write the same
# bytes:
#   - project.godot: config/name, run/main_scene (a uid:// is resolved to its scene),
#     the viewport size and the [input] actions;
#   - export_presets.cfg: the preset names and platforms;
#   - tools/*.sh other than verify.sh: each one's first header sentence;
#   - docs/agents/devices.md and CONTEXT-MAP.md or CONTEXT.md, when present;
#   - the feature map: every folder holding a product .tscn or .gd (not under
#     addons/, factory/, tools/, tests/, a dot folder or a .gdignore folder), its
#     scenes and scripts, and its mirrored tests/<folder>/ when that exists.
# Files come from git (tracked and untracked, not ignored) at a checkout's root,
# else from find. Exits 1 when it cannot write.
set -u

[ "$#" -eq 2 ] || {
	echo "usage: verify-skill.sh <project> <dir>" >&2
	exit 2
}
project="$1"
dir="$2"
skill="verify-$project"

# setting <section> <key>: the value of key in project.godot's [section], unquoted.
setting() {
	[ -f project.godot ] || return 0
	tr -d '\r' < project.godot | awk -v s="[$1]" -v k="$2" '
		/^\[/ { inside = ($0 == s); next }
		inside && index($0, k "=") == 1 { v = substr($0, length(k) + 2); gsub(/^"|"$/, "", v); print v; exit }
	'
}

files() {
	if [ -z "$(git rev-parse --show-prefix 2> /dev/null || echo no)" ]; then
		git ls-files -co --exclude-standard
	else
		find . -type f | sed 's#^\./##'
	fi | LC_ALL=C sort
}

# header <script>: the first sentence of the script's header comment.
header() {
	tr -d '\r' < "$1" | awk '
		NR == 1 && /^#!/ { next }
		!/^#/ || /^#[ \t]*$/ || /^#   / { exit }
		{ sub(/^#[ \t]*/, ""); text = text (text == "" ? "" : " ") $0 }
		END {
			i = index(text, ". ")
			if (i) text = substr(text, 1, i)
			sub(/:$/, ".", text)
			print text
		}
	'
}

listing="$(files)"

name="$(setting application config/name)"
[ -n "$name" ] || name="$project"
main="$(setting application run/main_scene)"
case "$main" in
	uid://*)
		scene="$(printf '%s\n' "$listing" | grep '\.tscn$' | while IFS= read -r f; do
			head -n 1 "$f" | grep -qF "uid=\"$main\"" && {
				printf 'res://%s\n' "$f"
				break
			}
		done)"
		[ -n "$scene" ] && main="$scene"
		;;
esac
width="$(setting display window/size/viewport_width)"
height="$(setting display window/size/viewport_height)"
actions="$([ -f project.godot ] && tr -d '\r' < project.godot | awk '
	/^\[/ { inside = ($0 == "[input]"); next }
	inside && /^[A-Za-z0-9_.\/]+=/ { sub(/=.*/, ""); printf "%s`%s`", (n++ ? ", " : ""), $0 }
')"
presets="$([ -f export_presets.cfg ] && tr -d '\r' < export_presets.cfg | awk '
	/^\[preset\.[0-9]+\]$/ { name = "" }
	/^name="/ { name = $0; sub(/^name="/, "", name); sub(/"$/, "", name) }
	/^platform="/ && name != "" { p = $0; sub(/^platform="/, "", p); sub(/"$/, "", p); printf "%s\"%s\" (%s)", (n++ ? ", " : ""), name, p; name = "" }
')"
tools="$(printf '%s\n' "$listing" | grep -E '^tools/[^/]+\.sh$' | grep -vxF tools/verify.sh)"
context=""
[ -f CONTEXT.md ] && context="CONTEXT.md"
[ -f CONTEXT-MAP.md ] && context="CONTEXT-MAP.md"
devices=""
[ -f docs/agents/devices.md ] && devices="docs/agents/devices.md"

mkdir -p "$dir" || exit 1

# A description has at most 200 characters (skill-budget.sh), so a long name is
# left out of it.
description="Launch, drive and inspect a running $name build (Godot), headless or on a device, and collect evidence. Use for smoke checks, bug repros and criteria that need a running build."
[ "${#description}" -le 200 ] ||
	description="Launch, drive and inspect a running build of this Godot project, headless or on a device, and collect evidence. Use for smoke checks, bug repros and criteria that need a running build."

{
	cat << EOF
---
name: $skill
description: $description
---

# $skill

Generated by \`bash factory/core/verify-skill.sh\` from the project's files; rerun it with \`--force\` after the layout changes (hand edits are lost then). Run everything from the project root. Godot is \`\$GODOT_BIN\`, set in \`tools/verify/local.env\` and pinned in \`tools/verify/pins\`; load it with \`set -a; . tools/verify/local.env; set +a\`. Scratch output goes under \`.godot/factory/\`, which is never tracked.

## Launch

EOF
	if [ -n "$main" ]; then
		echo "- **Main scene** (\`$main\`), headless: \`\"\$GODOT_BIN\" --headless --path . --quit-after 600 > .godot/factory/run.log 2>&1\`. The smoke step runs it for 300 frames: \`bash tools/verify.sh smoke\`."
	else
		echo "- **No main scene** in project.godot: name a scene on every launch."
	fi
	cat << 'EOF'
- **One scene**: put its `res://` path after `--path .`; the [feature map](feature-map.md) lists them.
- **With a window**, to watch or screenshot it: leave out `--headless`.
EOF
	if [ -n "$presets" ]; then
		echo "- **Playtest build**: \`bash tools/verify/playtest\` exports a debug build and prints its path. Presets: $presets."
	fi
	if [ -n "$devices" ]; then
		echo "- **On a device**: read \`$devices\` first; it says which device and how."
	fi
	if [ -n "$tools" ]; then
		echo "- **Project tools** (each script's header says how to use it):"
		printf '%s\n' "$tools" | while IFS= read -r t; do
			about="$(header "$t")"
			echo "  - \`bash $t\`${about:+: $about}"
		done
	fi
	cat << 'EOF'

## Doctor

When a launch fails, or before the first one on a machine:

1. `bash tools/verify.sh prepare`: tool locations, pins, the scope cross-check and Godot's import. Fix its findings first; `godot-missing` means `GODOT_BIN` in `tools/verify/local.env`.
2. `"$GODOT_BIN" --version` prints the version `tools/verify/pins` names.
3. A `SCRIPT ERROR` naming a class or a missing resource after a pull: rerun prepare, which reimports.
4. A device: `adb devices` lists it as `device` (not `unauthorized` or `offline`).

## Drive

- **Scripted, the durable way**: a gdUnit4 test with a scene runner (`scene_runner("res://...tscn")`, `simulate_frames`, `simulate_mouse_button_pressed`, `simulate_action_pressed`). Write it with `write-tests-godot`; run it with `bash tools/verify.sh test`.
- **A one-off probe**: a `SceneTree` script outside the project, run with `"$GODOT_BIN" --headless --path . -s <absolute path>.gd`. It loads a scene, steps frames, presses inputs with `Input.parse_input_event` and prints what it reads, then calls `quit()`.
EOF
	if [ -n "$actions" ]; then
		echo "- **Input actions** (project.godot): $actions."
	else
		echo "- **Input actions**: project.godot defines none; the scenes read raw input events (see their scripts)."
	fi
	if [ -n "$width" ] && [ -n "$height" ]; then
		echo "- **Viewport**: ${width}x${height}; on a device, scale tap coordinates to its screen."
	fi
	if [ -n "$devices" ]; then
		echo "- **On a device**: \`adb shell input tap|swipe ...\`. Tell the human first, and follow \`$devices\`."
	else
		echo "- **On a device**: \`adb shell input tap|swipe ...\`. Tell the human first: they may be using it."
	fi
	cat << 'EOF'

## Evidence

Evidence for a criterion is the command, its exit code, and the lines or files that show the behaviour. Quote them; never paraphrase a log.

- **Log**: Godot's output from the launch. An error is a `SCRIPT ERROR:` or `ERROR:` line with indented lines after it naming `res://<file>:<line>`; quote the whole block. Godot exits 0 even after a runtime error, so read the log, not the exit code.
- **Tests**: the test step's verdict lines, and gdUnit4's report under `.godot/factory/gdunit/`.
- **Screenshot**: in a windowed probe, `get_viewport().get_texture().get_image().save_png(path)` after a few frames; on a device, `adb exec-out screencap -p > <file>.png`.
- **State**: print the values the criterion names from a probe, one line each, with a fixed prefix you can grep.
EOF
	if [ -n "$tools" ] && printf '%s\n' "$tools" | grep -q 'log'; then
		echo "- **Device log**: capture it with the project's log tool above, run in the background, and read its file."
	fi
	cat << 'EOF'

## Cleanup

Leave the machine and the tree as you found them:

- Stop every Godot you started (`--quit-after`, `quit()`, or kill its PID). Check: `tasklist | grep -i godot` on Windows, `pgrep -l godot` elsewhere.
- Delete your probe scripts and screenshots, and anything you wrote outside `.godot/factory/`; `git status` shows only your intended changes.
EOF
	if [ -n "$tools" ] && printf '%s\n' "$tools" | grep -q 'stop'; then
		echo "- On a device: run the project's stop tool above, and check it reports nothing left behind."
	else
		echo "- On a device: stop any \`adb logcat\` you started, and leave the adb server running."
	fi
	cat << EOF

## Feature map

[\`feature-map.md\`](feature-map.md): each product folder with its scenes, scripts and mirrored tests.${context:+ Names follow \`$context\`.}
EOF
} > "$dir/SKILL.md" || exit 1

{
	echo "# $name feature map"
	echo
	echo "Generated with \`$skill\`. Each folder holding product scenes or scripts, with its mirrored tests (R8: \`tests/<folder>/\`).${main:+ The main scene is \`$main\`.}"
	echo
	echo "| Folder | Scenes | Scripts | Tests |"
	echo "| --- | --- | --- | --- |"
	printf '%s\n' "$listing" | awk '
		{ all[NR] = $0 }
		/(^|\/)\.gdignore$/ { d = $0; sub(/\.gdignore$/, "", d); ignored[d] = 1 }
		END {
			for (i = 1; i <= NR; i++) {
				f = all[i]
				if (f !~ /\.(tscn|gd)$/) continue
				if (f ~ /^(addons|factory|tools|tests)\// || f ~ /(^|\/)\./) continue
				skip = 0
				for (d in ignored) if (d == "" || index(f, d) == 1) skip = 1
				if (skip) continue
				n = split(f, part, "/")
				folder = (n == 1) ? "" : substr(f, 1, length(f) - length(part[n]))
				if (!(folder in seen)) { seen[folder] = 1; order[++count] = folder }
				if (f ~ /\.tscn$/) scenes[folder] = scenes[folder] (scenes[folder] == "" ? "" : ", ") part[n]
				else scripts[folder] = scripts[folder] (scripts[folder] == "" ? "" : ", ") part[n]
			}
			for (i = 1; i <= NR; i++) for (j = 1; j <= count; j++) {
				t = all[i]
				if (order[j] == "" ? t ~ /^tests\/[^\/]+$/ : index(t, "tests/" order[j]) == 1) tested[order[j]] = 1
			}
			for (j = 1; j <= count; j++) {
				folder = order[j]
				printf "| `%s` | %s | %s | %s |\n", (folder == "" ? "./" : folder), scenes[folder], scripts[folder], (folder in tested ? "`tests/" folder "`" : "none")
			}
		}
	' | LC_ALL=C sort
} > "$dir/feature-map.md" || exit 1
